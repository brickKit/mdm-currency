"""Writes currency/migrations/0002_iso4217.up.sql: the ISO 4217 table and the rate type spot.

    uv run --with babel==2.17.0 python -I scripts/iso4217.py <list-one.xml>

Codes, numeric codes, minor units and English names come from the official list (list one of the ISO 4217
maintenance agency, SIX: https://www.six-group.com/en/products-services/financial-information/data-standards.html),
given as a file so the output depends only on its inputs. Funds, precious metals and codes without a minor unit
("N.A.") are left out: they are not currencies a document is written in. The Chinese names and the cash rounding units
come from CLDR through Babel (the version is pinned above): CLDR's cash rounding is what the boundary card calls the
cash rounding unit (CHF 0.05). A currency listed by several countries is written once.
"""
from __future__ import annotations

import pathlib
import sys
import xml.etree.ElementTree as ET
from decimal import Decimal

from babel import Locale
from babel.core import get_global

OUT = pathlib.Path(__file__).resolve().parents[1] / "currency" / "migrations" / "0002_iso4217.up.sql"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main(source: str) -> None:
    root = ET.parse(source).getroot()
    published = root.get("Pblshd", "")
    rows: dict[str, tuple[str, int, str]] = {}
    for e in root.iter("CcyNtry"):
        code, num, unit, name = (e.findtext(t) for t in ("Ccy", "CcyNbr", "CcyMnrUnts", "CcyNm"))
        fund = e.find("CcyNm") is not None and e.find("CcyNm").get("IsFund") == "true"
        if not code or not num or not unit or not unit.isdigit() or fund:
            continue
        rows.setdefault(code, (num.zfill(3), int(unit), (name or "").strip()))
    fractions = get_global("currency_fractions")
    zh = Locale.parse("zh_Hans_CN")
    lines = [f"-- Generated by scripts/iso4217.py from ISO 4217 list one (published {published}) and CLDR (Babel): do not",
             "-- edit by hand. Funds, metals and codes without a minor unit are left out.",
             "INSERT INTO currency (code, numeric_code, minor_unit, cash_unit, name, names) VALUES"]
    values = []
    for code in sorted(rows):
        num, unit, name = rows[code]
        frac = fractions.get(code)
        cash = "NULL"
        if frac and frac[3]:  # (digits, rounding, cash digits, cash rounding)
            step = Decimal(frac[3]).scaleb(-frac[2])
            if step > 0 and step != Decimal(1).scaleb(-unit):
                cash = q(format(step.normalize(), "f"))
        zh_name = zh.currencies.get(code)
        names = "'{}'::jsonb" if not zh_name else "jsonb_build_object('zh-CN', " + q(zh_name) + ")"
        values.append(f"    ({q(code)}, {q(num)}, {unit}, {cash}, {q(name)}, {names})")
    lines.append(",\n".join(values) + ";")
    lines.append("")
    lines.append("INSERT INTO rate_type (code, name, names) VALUES ('spot', 'Spot', jsonb_build_object('zh-CN', '即期'));")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(values)} currencies -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
